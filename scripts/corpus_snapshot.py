_PROSE_SUFFIXES = frozenset({".md", ".markdown", ".rst", ".txt"})


def _default_source_type(candidate: _Candidate) -> str:
    if candidate.kind == "project":
        return _project_source_type(candidate)
    if candidate.kind == "code" and candidate.path.suffix.casefold() in _PROSE_SUFFIXES:
        return "doc"
    return _DEFAULT_SOURCE_TYPES[candidate.kind]


def _project_source_type(candidate: _Candidate) -> str:
    if candidate.path.name == "state.md":
        return "project-state"
    return "project-context"


def _validity_mapping(frontmatter: Mapping[str, object]) -> Mapping[str, object]:
    validity = frontmatter.get("validity", {})
    if validity is None:
        return {}
    if not isinstance(validity, Mapping):
        return {}
    return validity


def _metadata_instant(value: object) -> str | None:
    """A validity bound as text when it is an ISO date or datetime; otherwise absent."""
    text = _metadata_value(value)
    if text is None or _iso_parses(text):
        return text
    return None


def _iso_parses(text: str) -> bool:
    try:
        _parsed_iso(text)
    except ValueError:
        return False
    return True


_SCALAR_FIELDS = ("type", "project", "source_authority", "authority", "confidence", "status", "language", "lang")
_SCALAR_TYPES = (str, int, float, bool, date, datetime)


def _field_problems(mapping: Mapping[str, object]) -> list[str]:
    """Every metadata field the snapshot will ignore, named."""
    validity = mapping.get("validity")
    return _scalar_problems(mapping) + _validity_problems(validity) + _instant_problems(mapping, validity)


def _scalar_problems(mapping: Mapping[str, object]) -> list[str]:
    return [f"`{name}` is not a single value" for name in _SCALAR_FIELDS if _not_scalar(mapping.get(name))]


def _validity_problems(validity: object) -> list[str]:
    if validity is None or isinstance(validity, Mapping):
        return []
    return ["`validity` is not a mapping"]


def _instant_problems(mapping: Mapping[str, object], validity: object) -> list[str]:
    bounds = (mapping.get("valid_from"), mapping.get("valid_to"), *_validity_bounds(validity))
    return [f"`{str(value)[:40]}` is not an ISO date" for value in bounds if _not_instant(value)]


def _validity_bounds(validity: object) -> tuple[object, object]:
    if not isinstance(validity, Mapping):
        return None, None
    return validity.get("from"), validity.get("to")


def _not_scalar(value: object) -> bool:
    return value is not None and not isinstance(value, _SCALAR_TYPES)


def _not_instant(value: object) -> bool:
    return value is not None and _metadata_instant(value) is None


def frontmatter_problems(content: bytes) -> list[str]:
    """What the corpus cannot read in this page's metadata, for lint to name.

    The snapshot indexes such a page with the fields it could read; this is how
    the owner learns which fields were dropped and why.
    """
    if not _decodes_as_utf8(content):
        return ["page is not UTF-8"]
    read = read_frontmatter(content)
    if read.problem:
        return [read.problem]
    return _field_problems(read.mapping)


def _metadata_status(frontmatter: Mapping[str, object]) -> str:
    return (_metadata_value(frontmatter.get("status")) or "active").casefold()


def _metadata_language(frontmatter: Mapping[str, object]) -> str | None:
    language = _metadata_value(frontmatter.get("language") or frontmatter.get("lang"))
    if not language:
        return None
    return language.casefold()


_DAILY_DATE = re.compile(r"(\d{4}-\d{2}-\d{2})\.md$")


def _dated_by_name(candidate: _Candidate) -> str | None:
    """A daily entry's date is the one in its file name — the one certain date about it.

    Since 2026-09-09 that date is its `valid_from`, so the index's own
    since/as-of window reaches daily entries and a question's dates can bound
    a search. See `docs/research/2026-09-08-the-calendar-does-the-arithmetic.md`.
    """
    if candidate.kind != "daily":
        return None
    match = _DAILY_DATE.search(candidate.relative)
    if match is None:
        return None
    return match.group(1)


def _metadata(frontmatter: Mapping[str, object], candidate: _Candidate) -> SourceMetadata:
    validity = _validity_mapping(frontmatter)
    return SourceMetadata(
        type=_metadata_value(frontmatter.get("type")) or _default_source_type(candidate),
        project=_metadata_value(frontmatter.get("project")) or candidate.project,
        authority=_metadata_value(
            frontmatter.get("source_authority", frontmatter.get("authority"))
        ),
        confidence=_metadata_value(frontmatter.get("confidence")),
        status=_metadata_status(frontmatter),
        valid_from=_metadata_value(frontmatter.get("valid_from", validity.get("from")))
        or _dated_by_name(candidate),
        valid_to=_metadata_value(frontmatter.get("valid_to", validity.get("to"))),
        language=_metadata_language(frontmatter),
    )


def _parsed_iso(text: str) -> datetime:
    normalized = text.strip()
    if normalized.endswith("Z"):
        normalized = normalized[:-1] + "+00:00"
    try:
        return datetime.fromisoformat(normalized)
    except ValueError:
        return datetime.combine(date.fromisoformat(normalized), datetime_time.min)


def _dated_naive_datetime(value: date | datetime) -> datetime:
    if isinstance(value, datetime):
        return value
    return datetime.combine(value, datetime_time.min)


def _naive_datetime(value: str | date | datetime) -> datetime:
    if isinstance(value, (date, datetime)):
        return _dated_naive_datetime(value)
    if isinstance(value, str):
        return _parsed_iso(value)
    raise ValueError("as_of and validity values must be ISO dates or datetimes")


def _as_datetime(value: str | date | datetime | None) -> datetime | None:
    if value is None:
        return None
    result = _naive_datetime(value)
    if result.tzinfo is None:
        result = result.replace(tzinfo=timezone.utc)
    return result.astimezone(timezone.utc)


def _readable_bound(value: str | None) -> datetime | None:
    """A validity bound as an instant; one that does not parse is no bound.

    The text stays stored as written, so chunk rows do not change; only the
    reading tolerates it. See `docs/research/2026-09-14-a-bound-kept-as-written.md`.
    """
    if value is None or not _iso_parses(str(value)):
        return None
    return _as_datetime(value)


def _within_validity(metadata: SourceMetadata, instant: datetime) -> bool:
    start = _readable_bound(metadata.valid_from)
    end = _readable_bound(metadata.valid_to)
    if start is not None and start > instant:
        return False
    return end is None or instant < end


def _included(metadata: SourceMetadata, policy: SnapshotPolicy) -> bool:
    if policy.as_of is None:
        return policy.include_historical or not is_retired(metadata.status)
    instant = _as_datetime(policy.as_of)
    assert instant is not None
    return _within_validity(metadata, instant)


def _dominant(count: int, others: tuple[int, ...]) -> bool:
    return bool(count) and all(count >= other for other in others)


def _latin_only(latin: int, cyrillic: int, han: int) -> bool:
    return latin >= 3 and not cyrillic and not han


def _dominant_script_language(cyrillic: int, han: int, latin: int) -> str | None:
    if _dominant(cyrillic, (han, latin)):
        return "ru"
    if _dominant(han, (cyrillic, latin)):
        return "zh"
    return None


def _script_count(pattern: re.Pattern[str], text: str) -> int:
    """How many characters of one script the text holds, counted in C.

    `findall` builds a list of every single-character match — 10 215 lists and
    1.68 s of one cold answer on the installed vault, measured 2026-09-12, to
    produce three integers. Every class here matches exactly one character, so
    the length difference after removing them is the same count with no Python
    object per match.
    """
    return len(text) - len(pattern.sub("", text))


def _infer_language(text: str) -> str | None:
    cyrillic = _script_count(_CYRILLIC, text)
    han = _script_count(_HAN, text)
    latin = _script_count(_LATIN, text)
    dominant = _dominant_script_language(cyrillic, han, latin)
    if dominant is not None:
        return dominant
    return "en" if _latin_only(latin, cyrillic, han) else None


def _classify_language(*, explicit: str | None, path: Path, text: str) -> str | None:
    return explicit or language_for_path(path) or _infer_language(text)


def _clean_heading(raw: bytes | None) -> str:
    title = (raw or b"").decode("utf-8", errors="strict").strip()
    return _CLOSING_HASHES.sub("", title)


def _closing_fence(body: bytes, character: bytes, length: int) -> bool:
    pattern = (
        rb"[ ]{0,3}"
        + re.escape(character)
        + rb"{" + str(length).encode("ascii") + rb",}[ \t]*"
    )
    return re.fullmatch(pattern, body) is not None


def _opening_fence(body: bytes):
    """The fence that opens a block, or None — a backtick in the info string is not one."""
    opening = _FENCE.fullmatch(body)
    if opening is None:
        return None
    if opening.group(1).startswith(b"`") and b"`" in opening.group(2):
        return None
    return opening


class _HeadingScan:
    """The fence state machine that decides which lines may be headings."""

    def __init__(self) -> None:
        self.character: bytes | None = None
        self.length = 0
        self.headings: list[re.Match[bytes]] = []

    def line(self, content: bytes, offset: int, end: int) -> None:
        body = content[offset:end].rstrip(b"\r\n")
        if self.character is not None:
            self._maybe_close(body)
            return
        opening = _opening_fence(body)
        if opening is not None:
            self.character = opening.group(1)[:1]
            self.length = len(opening.group(1))
            return
        self._maybe_heading(content, offset, end)

    def _maybe_close(self, body: bytes) -> None:
        if _closing_fence(body, self.character, self.length):
            self.character = None
            self.length = 0

    def _maybe_heading(self, content: bytes, offset: int, end: int) -> None:
        heading = _HEADING.match(content, offset, end)
        if heading is None:
            return
        if len(self.headings) >= MAX_CORPUS_HEADINGS:
            raise ValueError("corpus heading row ceiling exceeded")
        self.headings.append(heading)


def _markdown_headings(
    content: bytes,
    start: int,
    *,
    deadline: float | None,
    cancelled: Callable[[], bool] | None,
) -> list[re.Match[bytes]]:
    scan = _HeadingScan()
    for offset, end in _line_spans(content, start):
        _check_processing_stop(deadline, cancelled)
        scan.line(content, offset, end)
    return scan.headings


def _headings_when_enabled(
    content: bytes,
    searchable_start: int,
    heading_enabled: bool,
    deadline: float | None,
    cancelled: Callable[[], bool] | None,
) -> list[re.Match[bytes]]:
    if not heading_enabled:
        return []
    return _markdown_headings(
        content, searchable_start, deadline=deadline, cancelled=cancelled
    )


def _leading_span(
    content: bytes, searchable_start: int, first_heading: int
) -> list[tuple[int, int, tuple[str, ...]]]:
    if content[searchable_start:first_heading].strip():
        return [(searchable_start, first_heading, ())]
    return []


def _heading_end(headings: list[re.Match[bytes]], index: int, content: bytes) -> int:
    if index + 1 < len(headings):
        return headings[index + 1].start()
    return len(content)


def _updated_ancestry(
    ancestry: list[tuple[int, str]], level: int, title: str
) -> list[tuple[int, str]]:
    kept = [item for item in ancestry if item[0] < level]
    kept.append((level, title))
    return kept


def _append_heading_span(
    spans: list, content: bytes, heading: re.Match[bytes], end: int, ancestry: list
) -> None:
    if not content[heading.start():end].strip():
        return
    if len(spans) >= MAX_CORPUS_CHUNKS:
        raise ValueError("corpus chunk row ceiling exceeded")
    spans.append((heading.start(), end, tuple(item[1] for item in ancestry)))


# A retrieval unit above this many bytes is cut at a paragraph boundary. About
# 1 024 tokens — the top of the 512–1 024 band 2026 benchmarking reports for
# analytical and multi-hop queries, taken at the top rather than the middle
# because conversational text holds a topic longer than prose does.
#
# Measured on this vault: a captured session arrives as one heading span of
# about 10 KB, roughly 2 500 tokens, against a 28 672-byte answer budget — so a
# median of two units reach the answer model, and the categories that need facts
# from more than one session score 0.0216 and 0.0988 by judge. Two and a half
# times the recommended band is not merely coarser than the reference designs;
# it is outside the range anyone reports good results in.
#
# Turn-level was the other candidate and the sources argue against it: too
# fine-grained is fragmentary, and session-level beats turn-level on its own.
# A paragraph boundary in a rendered transcript falls between speaker turns and
# between topics inside a long one, which is the closest thing to a topically
# coherent unit that costs no model call.
# See `docs/research/2026-09-02-the-unit-of-retrieval.md`.
MAX_SPAN_BYTES = 4096


def _character_boundary(content: bytes, index: int) -> int:
    """The largest index at or below `index` that begins a UTF-8 character.

    A continuation byte is `10xxxxxx`, and a character is at most four bytes,
    so walking back at most three is enough to land on a start byte.
    """
    if index >= len(content):
        return index
    floor = max(index - 3, 0)
    while index > floor and content[index] & 0xC0 == 0x80:
        index -= 1
    return index


def _paragraph_cut(content: bytes, start: int, ceiling: int) -> int:
    """The last paragraph break at or before the ceiling, then the last line.

    When a span carries neither, it is cut at the ceiling — and the ceiling is a
    byte count, so on any text that is not ASCII it lands inside a character
    about three times in four. Measured on this vault 2026-09-05: the cut fell
    at byte 4095 of a Russian paragraph, `_chunks` decoded the span strictly and
    raised, and the exception travelled all the way up through the corpus
    collector to abort the nightly generation build. Nothing was published from
    2026-08-30 onward, retrieval fell back to its lexical leg, and the only
    trace was a per-row `fallback_reason` field and one line in `doctor`.

    The two markers are ASCII and therefore already safe. It is the fallback
    that has to be walked back onto a character boundary.
    """
    window = content[start:ceiling]
    for marker in (b"\n\n", b"\n"):
        cut = window.rfind(marker)
        if cut > 0:
            return start + cut + len(marker)
    return _character_boundary(content, ceiling)


# A rendered conversation starts every turn with one of these markers at the
# start of a line. Each turn is a chunk: the user's turn is a 300-byte key that
# states the fact, and the reply it got is the value delivered beside it
# (Dense X Retrieval, arXiv:2312.06648; small-to-big retrieval). The 2026-09-02
# decision took 4 KB paragraph pieces over turns because a turn alone reads as
# a fragment; a turn is found here and read with its partner.
# See `docs/research/2026-09-08-small-keys-large-values-and-a-loop-that-stops.md`.
TURN_MARKERS = (b"**user:**", b"**assistant:**")
# A turn shorter than this stays with the turn before it: a bare "thanks" is
# not a unit worth finding on its own.
MIN_ROUND_BYTES = 160
# The user's own turns earn a chunk far sooner: they carry the facts questions ask about.
# Measured on LongMemEval 2026-09-16: of 896 evidence turns only 2 are shorter than this,
# while 4 % of all user turns are — the bare acknowledgements, which still fold.
MIN_USER_ROUND_BYTES = 48


def _marker_offsets(content: bytes, marker: bytes, start: int, end: int) -> list[int]:
    found: list[int] = []
    offset = content.find(marker, start, end)
    while offset != -1:
        found.append(offset)
        offset = content.find(marker, offset + len(marker), end)
    return found


def _begins_a_line(content: bytes, offset: int, start: int) -> bool:
    return offset > start and content[offset - 1 : offset] == b"\n"


def _round_starts(content: bytes, start: int, end: int) -> list[int]:
    """Offsets inside the span where a turn begins a line, the span's own start excluded."""
    offsets: list[int] = []
    for marker in TURN_MARKERS:
        offsets.extend(_marker_offsets(content, marker, start, end))
    return sorted(offset for offset in offsets if _begins_a_line(content, offset, start))


def _starts_a_user_turn(content: bytes, offset: int) -> bool:
    return content.startswith(TURN_MARKERS[0], offset)


def _round_bound(content: bytes, cut: int) -> int:
    """How long a round must be to earn a chunk, by whose turn begins it."""
    if _starts_a_user_turn(content, cut):
        return MIN_USER_ROUND_BYTES
    return MIN_ROUND_BYTES


def _kept_cut(content: bytes, cut: int, following: int) -> bool:
    """A stated fact begins a chunk; a bare acknowledgement folds into the round before.

    A 91-character user turn used to end a 2 101-character chunk that began with an
    assistant reply, and the fact it stated ranked 53rd. 91 % of the stand's evidence turns
    are user turns, and the reader is handed the round either way. Research:
    `docs/research/2026-09-16-a-user-turn-always-starts-its-own-chunk.md`.
    """
    return following - cut >= _round_bound(content, cut)


def _without_short_preamble(cuts: list[int], start: int) -> list[int]:
    """The heading and its stamp fold into the first round after them."""
    if not cuts or cuts[0] - start >= MIN_ROUND_BYTES:
        return cuts
    return cuts[1:]


def _long_enough_cuts(content: bytes, cuts: list[int], start: int, end: int) -> list[int]:
    """The cuts that begin a round worth finding on its own."""
    kept = _without_short_preamble(cuts, start)
    bounds = [*kept, end]
    return [cut for cut, following in zip(kept, bounds[1:]) if _kept_cut(content, cut, following)]


def _round_spans(content: bytes, span: tuple) -> list[tuple[int, int, tuple[str, ...]]]:
    """The span cut at every user turn, short rounds folded into the one before."""
    start, end, ancestry = span
    rounds: list[tuple[int, int, tuple[str, ...]]] = []
    for cut in _long_enough_cuts(content, _round_starts(content, start, end), start, end):
        rounds.append((start, cut, ancestry))
        start = cut
    rounds.append((start, end, ancestry))
    return rounds


def _split_span(content: bytes, span: tuple) -> list[tuple[int, int, tuple[str, ...]]]:
    """One span as rounds, then as bounded pieces, each keeping its heading ancestry."""
    pieces: list[tuple[int, int, tuple[str, ...]]] = []
    for round_span in _round_spans(content, span):
        pieces.extend(_bounded_pieces(content, round_span))
    return pieces


def _bounded_pieces(content: bytes, span: tuple) -> list[tuple[int, int, tuple[str, ...]]]:
    """One span as pieces of at most MAX_SPAN_BYTES, cut at paragraph boundaries."""
    start, end, ancestry = span
    pieces: list[tuple[int, int, tuple[str, ...]]] = []
    while end - start > MAX_SPAN_BYTES:
        cut = _paragraph_cut(content, start, start + MAX_SPAN_BYTES)
        if cut <= start:
            break
        pieces.append((start, cut, ancestry))
        start = cut
    pieces.append((start, end, ancestry))
    return pieces


def _bounded_spans(content: bytes, spans: list) -> list:
    bounded: list[tuple[int, int, tuple[str, ...]]] = []
    for span in spans:
        bounded.extend(_split_span(content, span))
    if len(bounded) > MAX_CORPUS_CHUNKS:
        raise ValueError("corpus chunk row ceiling exceeded")
    return bounded


def _retrieval_spans(
    content: bytes,
    searchable_start: int,
    *,
    heading_enabled: bool,
    deadline: float | None,
    cancelled: Callable[[], bool] | None,
) -> tuple[tuple[int, int, tuple[str, ...]], ...]:
    headings = _headings_when_enabled(
        content, searchable_start, heading_enabled, deadline, cancelled
    )
    first_heading = headings[0].start() if headings else len(content)
    spans = _leading_span(content, searchable_start, first_heading)
    ancestry: list[tuple[int, str]] = []
    for index, heading in enumerate(headings):
        _check_processing_stop(deadline, cancelled)
        ancestry = _updated_ancestry(
            ancestry, len(heading.group(1)), _clean_heading(heading.group(2))
        )
        _append_heading_span(
            spans, content, heading, _heading_end(headings, index, content), ancestry
        )
    return tuple(_bounded_spans(content, spans))


def _markdown_head(
    source_path: str,
    content: bytes,
    deadline: float | None,
    cancelled: Callable[[], bool] | None,
) -> tuple[bool, int, dict[str, Any]]:
    """(is markdown, where the searchable text starts, the frontmatter)."""
    is_markdown = PurePosixPath(source_path).suffix.casefold() == ".md"
    content.decode("utf-8", errors="strict")
    if not is_markdown:
        return False, 0, {}
    frontmatter, searchable_start = _frontmatter(
        content, deadline=deadline, cancelled=cancelled
    )
    return True, searchable_start, frontmatter


def canonical_retrieval_spans(
    source_path: str,
    content: bytes,
    *,
    deadline: float | None = None,
    cancelled: Callable[[], bool] | None = None,
) -> tuple[tuple[int, int, tuple[str, ...]], ...]:
    """Return the shared canonical chunk ranges for captured source bytes."""
    if not isinstance(source_path, str) or not source_path:
        raise ValueError("source_path must be a non-empty string")
    if not isinstance(content, bytes) or len(content) > MAX_CORPUS_FILE_BYTES:
        raise ValueError("captured retrieval source must be bounded bytes")
    is_markdown, searchable_start, _frontmatter_value = _markdown_head(
        source_path, content, deadline, cancelled
    )
    return _retrieval_spans(
        content,
        searchable_start,
        heading_enabled=is_markdown,
        deadline=deadline,
        cancelled=cancelled,
    )


# One walk per source instead of two per chunk. `content.count(b"\n", 0, start)`
# rescans from byte zero for every chunk of every source, which on the installed
# vault was 11 124 scans and 1.16 s of a single 3.2 s code answer — the largest
# single cost left in it (measured 2026-09-12). The newline offsets are a fact
# about the source; taken once, each chunk's line is a binary search. The
# numbers produced are identical, which the existing chunk tests hold.
def _newline_offsets(content: bytes) -> tuple[int, ...]:
    offsets: list[int] = []
    position = content.find(b"\n")
    while position >= 0:
        offsets.append(position)
        position = content.find(b"\n", position + 1)
    return tuple(offsets)


def _line_at(offsets: tuple[int, ...], index: int) -> int:
    """The 1-based line the byte at `index` starts on."""
    return bisect_left(offsets, index) + 1


def _chunks(
    source: SourceRecord,
    metadata: SourceMetadata,
    content: bytes,
    searchable_start: int,
    *,
    heading_enabled: bool = True,
    extractor_version: str = EXTRACTOR_VERSION,
    deadline: float | None = None,
    cancelled: Callable[[], bool] | None = None,
) -> tuple[RetrievalChunk, ...]:
    result = []
    offsets = _newline_offsets(content)
    spans = _retrieval_spans(
        content,
        searchable_start,
        heading_enabled=heading_enabled,
        deadline=deadline,
        cancelled=cancelled,
    )
    for start, end, heading_ancestry in spans:
        _check_processing_stop(deadline, cancelled)
        span = content[start:end]
        text = span.decode("utf-8", errors="strict")
        span_hash = _sha256(span)
        chunk_id = canonical_chunk_id(
            source_id=source.logical_id,
            source_path=source.relative_path,
            byte_start=start,
            byte_end=end,
            span_sha256=span_hash,
            extractor_version=extractor_version,
        )
        result.append(
            RetrievalChunk(
                id=chunk_id,
                source_id=source.logical_id,
                source_path=source.relative_path,
                parent_page=source.relative_path,
                heading_ancestry=heading_ancestry,
                byte_start=start,
                byte_end=end,
                line_start=_line_at(offsets, start),
                line_end=_line_at(offsets, end),
                text=text,
                source_sha256=source.sha256,
                span_sha256=span_hash,
                type=metadata.type,
                project=metadata.project,
                authority=metadata.authority,
                confidence=metadata.confidence,
                status=metadata.status,
                valid_from=metadata.valid_from,
                valid_to=metadata.valid_to,
                language=source.language or _infer_language(text),
            )
        )
    return tuple(result)


_SOURCE_KIND_PREFIXES = (
    (("knowledge", "raw", "sessions"), "session"),
    (("knowledge", "notes"), "note"),
    (("knowledge", "daily"), "daily"),
)


def _project_part(path: PurePosixPath) -> str | None:
    if len(path.parts) > 3:
        return path.parts[2]
    return None


def _source_kind(path: PurePosixPath) -> tuple[str, str | None]:
    for prefix, kind in _SOURCE_KIND_PREFIXES:
        if path.parts[: len(prefix)] == prefix:
            return kind, None
    if path.parts[:2] == ("knowledge", "projects"):
        return "project", _project_part(path)
    return "code", None


def _require_canonical_source(
    source_id: str,
    source_path: str,
    path: PurePosixPath,
    content: bytes,
    source_sha256: str,
) -> None:
    if not source_id or source_id != f"source:{source_path}" or not path.parts:
        raise ValueError("source identity is not canonical")
    if _sha256(content) != source_sha256:
        raise ValueError("source bytes do not match their canonical hash")


def _canonical_source_record(
    source_id: str,
    source_path: str,
    source_sha256: str,
    content: bytes,
    *,
    is_markdown: bool,
    metadata: SourceMetadata,
    candidate: _Candidate,
    searchable_start: int,
) -> SourceRecord:
    language = _classify_language(
        explicit=metadata.language,
        path=candidate.path,
        text=content[searchable_start:].decode("utf-8", errors="strict"),
    )
    return SourceRecord(
        source_id,
        source_path,
        source_sha256,
        len(content),
        "text/markdown" if is_markdown else "text/plain",
        language,
        None,
    )


def canonical_retrieval_chunks(
    *,
    source_id: str,
    source_path: str,
    source_sha256: str,
    content: bytes,
    extractor_version: str = EXTRACTOR_VERSION,
    deadline: float | None = None,
    cancelled: Callable[[], bool] | None = None,
) -> tuple[RetrievalChunk, ...]:
    """Reconstruct every canonical chunk field from authoritative source bytes."""
    path = PurePosixPath(source_path)
    _require_canonical_source(source_id, source_path, path, content, source_sha256)
    kind, project = _source_kind(path)
    is_markdown, searchable_start, frontmatter = _markdown_head(
        source_path, content, deadline, cancelled
    )
    candidate = _Candidate(Path(*path.parts), source_path, kind, project, ())
    metadata = _metadata(frontmatter, candidate)
    source = _canonical_source_record(
        source_id,
        source_path,
        source_sha256,
        content,
        is_markdown=is_markdown,
        metadata=metadata,
        candidate=candidate,
        searchable_start=searchable_start,
    )
    return _chunks(
        source,
        metadata,
        content,
        searchable_start,
        heading_enabled=is_markdown,
        extractor_version=extractor_version,
        deadline=deadline,
        cancelled=cancelled,
    )


def _normalize_explicit_paths(
    values: Iterable[str | Path],
    normalize: Callable[[str | Path], str],
    *,
    label: str,
) -> tuple[str, ...]:
    normalized = []
    seen = set()
    for value in values:
        path = normalize(value)
        if path in seen:
            raise ValueError(f"duplicate {label}: {path}")
        seen.add(path)
        normalized.append(path)
    return tuple(sorted(normalized))


def _require_daily_files(normalized_daily: tuple[str, ...]) -> None:
    for path in normalized_daily:
        if not path.endswith(".md") or path == "knowledge/daily":
            raise ValueError("daily evidence must name an explicit Markdown file")


def _require_no_nested_root(root: str, others: tuple[str, ...]) -> None:
    for other in others:
        if other.startswith(root + "/"):
            raise ValueError(f"overlapping code roots are forbidden: {root}, {other}")


def _require_disjoint_roots(normalized_code: tuple[str, ...]) -> None:
    for index, root in enumerate(normalized_code):
        _require_no_nested_root(root, normalized_code[index + 1 :])


def _as_of_text(as_of: str | date | datetime | None) -> str | None:
    value = _metadata_value(as_of)
    if value is None:
        return None
    parsed = _as_datetime(value)
    assert parsed is not None
    return parsed.isoformat().replace("+00:00", "Z")


def _policy(
    *,
    daily_paths: Iterable[str | Path],
    code_roots: Iterable[str | Path],
    approved_code_roots: Iterable[str],
    include_historical: bool,
    as_of: str | date | datetime | None,
    max_files: int,
    max_file_bytes: int,
    max_total_bytes: int,
    max_entries: int,
    max_directories: int,
    max_depth: int,
) -> SnapshotPolicy:
    if not isinstance(include_historical, bool):
        raise ValueError("include_historical must be boolean")
    normalized_daily = _normalize_explicit_paths(
        daily_paths,
        lambda path: _relative_posix(path, prefixes=("knowledge/daily",)),
        label="daily evidence path",
    )
    _require_daily_files(normalized_daily)
    approved = tuple(sorted({str(name) for name in approved_code_roots}))
    normalized_code = _normalize_explicit_paths(
        code_roots, lambda path: _code_root(path, approved), label="code root"
    )
    _require_disjoint_roots(normalized_code)
    return SnapshotPolicy(
        daily_paths=normalized_daily,
        code_roots=normalized_code,
        include_historical=include_historical,
        as_of=_as_of_text(as_of),
        max_files=_positive_limit(max_files, "max_files"),
        max_file_bytes=_positive_limit(max_file_bytes, "max_file_bytes"),
        max_total_bytes=_positive_limit(max_total_bytes, "max_total_bytes"),
        max_entries=_positive_limit(max_entries, "max_entries"),
        max_directories=_positive_limit(max_directories, "max_directories"),
        max_depth=_positive_limit(max_depth, "max_depth", allow_zero=True),
    )


def _candidate_content(candidate: _Candidate, policy: SnapshotPolicy, label: str) -> bytes:
    if candidate.content is not None:
        return candidate.content
    _verify_seal(candidate.seal)
    content = _sealed_source_bytes(candidate.path, policy.max_file_bytes, label)
    _verify_seal(candidate.seal)
    return content


def _sealed_source_bytes(path: Path, max_bytes: int, label: str) -> bytes:
    """A source read by path, where a file being written is a changed corpus.

    This is the reader where directory descriptors are not available. The
    descriptor walk already calls a file that moves under it `CorpusChanged`,
    which is retried and then named; here the same event arrived as a bare
    `PermissionError`, so the capture died on the first write and the refusal
    blamed the repository's size. Research:
    `docs/research/2026-09-17-five-failures-only-the-other-systems-showed.md`.
    """
    try:
        return read_stable_bytes(path, max_bytes, label=label)
    except SourceChangedDuringRead as error:
        raise CorpusChanged(f"corpus source changed during read: {path.name}") from error


def _captured_record(
    candidate: _Candidate,
    content: bytes,
    metadata: SourceMetadata,
    is_markdown: bool,
    searchable_start: int,
    digest: str,
) -> SourceRecord:
    language = _classify_language(
        explicit=metadata.language,
        path=candidate.path,
        text=content[searchable_start:].decode("utf-8", errors="strict"),
    )
    return SourceRecord(
        logical_id=f"source:{candidate.relative}",
        relative_path=candidate.relative,
        sha256=digest,
        size=len(content),
        media_type="text/markdown" if is_markdown else "text/plain",
        language=language,
        git_oid=None,
    )


class _Capture:
    """Accumulates captured sources and their chunks under the policy limits."""

    def __init__(
        self,
        policy: SnapshotPolicy,
        deadline: float,
        cancelled: Callable[[], bool] | None,
    ) -> None:
        self.policy = policy
        self.deadline = deadline
        self.cancelled = cancelled
        self.captured: list[CapturedSource] = []
        self.chunks: list[RetrievalChunk] = []
        self.hashes: dict[str, str] = {}
        self.total = 0

    def add(self, candidate: _Candidate) -> None:
        content = _candidate_content(candidate, self.policy, "corpus source")
        self._count_bytes(len(content))
        is_markdown = candidate.path.suffix.casefold() == ".md"
        # A page that is not text costs itself, as any other undecodable file does.
        readable = _decodes_as_utf8(content)
        frontmatter, searchable_start = self._head(content, is_markdown and readable)
        metadata = _metadata(frontmatter, candidate)
        digest = _sha256(content)
        self.hashes[candidate.relative] = digest
        if readable and _included(metadata, self.policy):
            self._store(candidate, content, metadata, is_markdown, searchable_start, digest)

    def _head(self, content: bytes, is_markdown: bool) -> tuple[dict[str, Any], int]:
        if not is_markdown:
            return {}, 0
        return _frontmatter(content, deadline=self.deadline, cancelled=self.cancelled)

    def _count_bytes(self, size: int) -> None:
        self.total += size
        if self.total > self.policy.max_total_bytes:
            raise ValueError("corpus total byte limit exceeded")

    def _store(
        self,
        candidate: _Candidate,
        content: bytes,
        metadata: SourceMetadata,
        is_markdown: bool,
        searchable_start: int,
        digest: str,
    ) -> None:
        record = _captured_record(
            candidate, content, metadata, is_markdown, searchable_start, digest
        )
        self.captured.append(CapturedSource(record, metadata, content))
        source_chunks = _chunks(
            record,
            metadata,
            content,
            searchable_start,
            heading_enabled=is_markdown,
            deadline=self.deadline,
            cancelled=self.cancelled,
        )
        if len(self.chunks) + len(source_chunks) > MAX_CORPUS_CHUNKS:
            raise ValueError("corpus chunk row ceiling exceeded")
        self.chunks.extend(source_chunks)


def _require_stable_membership(
    candidates: tuple[_Candidate, ...], current: tuple[_Candidate, ...]
) -> None:
    if tuple(item.relative for item in candidates) != tuple(
        item.relative for item in current
    ):
        raise CorpusChanged("corpus membership changed during collection")


def _require_stable_content(
    current: tuple[_Candidate, ...],
    policy: SnapshotPolicy,
    hashes: dict[str, str],
    deadline: float,
) -> None:
    for candidate in current:
        _check_deadline(deadline)
        content = _candidate_content(candidate, policy, "corpus validation source")
        if _sha256(content) != hashes[candidate.relative]:
            raise CorpusChanged(
                f"corpus source changed during collection: {candidate.relative}"
            )


def _capture(
    vault: Path,
    policy: SnapshotPolicy,
    deadline: float,
    cancelled: Callable[[], bool] | None,
) -> CorpusSnapshot:
    candidates = _discover(vault, policy, deadline)
    capture = _Capture(policy, deadline, cancelled)
    for candidate in candidates:
        _check_deadline(deadline)
        capture.add(candidate)
    _check_deadline(deadline)
    current = _discover(vault, policy, deadline)
    _require_stable_membership(candidates, current)
    _require_stable_content(current, policy, capture.hashes, deadline)
    corpus_hash = canonical_source_manifest_sha256(
        (source.record for source in capture.captured), policy
    )
    return CorpusSnapshot(
        tuple(capture.captured), tuple(capture.chunks), corpus_hash, policy
    )


# A capture reads every source, then re-reads every source and refuses the
# snapshot if anything moved. That fence is right and stays: it is what proves a
# published generation describes a moment the vault really passed through.
#
# What was wrong was surrendering the first time it fired. Measured 2026-09-05: a
# pass costs 3.5-3.6 seconds and never fails on a quiet vault, but a session
# appends to today's daily log on every tool call, so under maintenance the pass
# loses the race and the whole nightly build died with it — every night from
# 2026-08-30, leaving no active generation and retrieval on its lexical leg
# alone. Nothing about the fence changed; the vault outgrew it.
#
# Snapshot isolation, in every MVCC engine, means a consistent view from the
# point a transaction started — not a world that holds still until it commits.
# So: take another pass. Fail only if the vault never holds still for one.
MAX_CAPTURE_PASSES = 4


def _captured_after_retries(
    root: Path,
    policy: SnapshotPolicy,
    deadline: float,
    cancelled: Callable[[], bool] | None,
) -> CorpusSnapshot:
    """One capture that describes a real instant, retried while the vault moves."""
    last: CorpusChanged | None = None
    for _ in range(MAX_CAPTURE_PASSES):
        _check_processing_stop(deadline, cancelled)
        try:
            return _capture(root, policy, deadline, cancelled)
        except CorpusChanged as exc:
            last = exc
    raise CorpusChanged(f"corpus never held still for one pass: {last}")


def collect_corpus(
    vault: Path,
    *,
    daily_paths: Iterable[str | Path] = (),
    code_roots: Iterable[str | Path] = (),
    approved_code_roots: Iterable[str] = APPROVED_CODE_ROOTS,
    include_historical: bool = False,
    as_of: str | date | datetime | None = None,
    max_files: int = MAX_CORPUS_FILES,
    max_file_bytes: int = MAX_CORPUS_FILE_BYTES,
    max_total_bytes: int = MAX_CORPUS_TOTAL_BYTES,
    max_entries: int = MAX_CORPUS_INSPECTED_ENTRIES,
    max_directories: int = MAX_CORPUS_DIRECTORIES,
    max_depth: int = MAX_CORPUS_DEPTH,
    deadline: float | None = None,
    deadline_seconds: float | None = None,
    coordinator: object | None = None,
    cancelled: Callable[[], bool] | None = None,
) -> CorpusSnapshot:
    """Capture one immutable corpus and reject any change before returning it."""
    root = Path(vault).resolve(strict=True)
    if not stat.S_ISDIR(_safe_info(root).st_mode):
        raise ValueError("vault must be a regular directory")
    selected_policy = _policy(
        daily_paths=daily_paths,
        code_roots=code_roots,
        approved_code_roots=approved_code_roots,
        include_historical=include_historical,
        as_of=as_of,
        max_files=max_files,
        max_file_bytes=max_file_bytes,
        max_total_bytes=max_total_bytes,
        max_entries=max_entries,
        max_directories=max_directories,
        max_depth=max_depth,
    )
    selected_deadline = _deadline_value(deadline, deadline_seconds)
    if coordinator is not None:
        _check_deadline(selected_deadline)
        remaining = max(0.0, selected_deadline - time.monotonic())
        gate = coordinator.writer_gate(wait_seconds=remaining)
    else:
        gate = contextlib.nullcontext()
    with gate:
        _check_processing_stop(selected_deadline, cancelled)
        return _captured_after_retries(
            root, selected_policy, selected_deadline, cancelled
        )


def validate_live_snapshot(
    snapshot: CorpusSnapshot,
    vault: Path,
    *,
    daily_paths: Iterable[str | Path] | None = None,
    code_roots: Iterable[str | Path] | None = None,
    include_historical: bool | None = None,
    as_of: str | date | datetime | None = None,
    max_files: int | None = None,
    max_file_bytes: int | None = None,
    max_total_bytes: int | None = None,
    max_entries: int | None = None,
    max_directories: int | None = None,
    max_depth: int | None = None,
    deadline: float | None = None,
    deadline_seconds: float | None = None,
    coordinator: object | None = None,
    cancelled: Callable[[], bool] | None = None,
) -> None:
    """Refuse a snapshot that does not describe itself, immediately before publication.

    This used to re-collect the entire live corpus and demand it be byte-identical
    to the snapshot taken minutes earlier. That asks the vault to hold still for
    the length of a build, which no vault in use ever does — and measured on this
    one, none has since 2026-08-30. Every nightly build died here, nothing was
    activated, and retrieval fell back to its lexical leg for five days while the
    complete vectors sat unreachable on disk.

    A snapshot is a snapshot. Snapshot isolation, in every MVCC engine, means a
    consistent view from the point a read started, not a world frozen until it
    commits; Lucene commits are point-in-time for the same reason. What a
    published generation owes its readers is that it describes a moment the vault
    really passed through — which the collection fence already proves, twice,
    before this is ever called.

    What it does not owe them is being the newest moment. A document written
    after the snapshot is absent until the next build, and no check here could
    find it: there is nothing yet to check. That is the price of a lagging index
    and it is the only one we pay, because a source the vault has since moved on
    from is re-read and dropped before its text can reach the model — see
    `query_memory._FreshSources`.

    So what is verified here is that the snapshot is what it says it is: its
    sources still hash to the manifest recorded in `corpus_sha256`. That is
    tamper-evidence, it costs no I/O, and it removes a second full collection
    from every publication.
    """
    if not isinstance(snapshot, CorpusSnapshot):
        raise TypeError("snapshot must be a CorpusSnapshot")
    recomputed = canonical_source_manifest_sha256(
        (source.record for source in snapshot.sources), snapshot.policy
    )
    if recomputed != snapshot.corpus_sha256:
        raise CorpusChanged("snapshot does not match its own source manifest")
