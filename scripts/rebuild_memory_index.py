"""Regenerate `knowledge/index.md` from `knowledge/notes/**/*.md`.

Supports both flat notes (current public layout) and typed subdirs
(concepts/decisions/patterns/debugging/qa) when present.
"""
from __future__ import annotations

import re
import sys
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bounded_io import MAX_KNOWLEDGE_PAGE_BYTES, read_stable_bytes  # noqa: E402
from claim_tree_manifest import snapshot_claim_tree_with_content  # noqa: E402
from markdown_transaction import (  # noqa: E402
    ABSENT,
    TransactionDriftError,
    TransactionFailure,
    mutate_knowledge,
    stable_operation_id,
)
from memory_state import ROOT  # noqa: E402
from page_status import is_retired  # noqa: E402
from reliable_memory import sha256_bytes  # noqa: E402
from settings import raise_hint, setting_value  # noqa: E402

memory = ROOT / "knowledge"
knowledge = memory / "notes"
out = memory / "index.md"

TYPE_SECTIONS = {
    "concept": "Concepts",
    "decision": "Decisions",
    "pattern": "Patterns",
    "debugging": "Debugging",
    "qa": "Q&A",
    "entity": "Entities",
    "synthesis": "Syntheses",
    "comparison": "Comparisons",
    "connection": "Connections",
    "workflow": "Workflows",
    "raw-source": "Raw sources",
}

SUMMARY_RE = re.compile(r"^One-sentence summary:\s*(.+?)\s*$", re.MULTILINE)
TYPE_RE = re.compile(r"^type:\s*(.+?)\s*$", re.MULTILINE)
STATUS_RE = re.compile(r"^status:\s*(.+?)\s*$", re.MULTILINE)
SKIP_NAMES = {"README.md", "index.md", "log.md"}
MAX_PAGE_BYTES = MAX_KNOWLEDGE_PAGE_BYTES
# `knowledge/index.md` as this module writes it and the compile reads it back.
MAX_INDEX_BYTES = 4 * 1024 * 1024
MAX_REBUILD_ATTEMPTS = 4


INDEX_HEADER = (
    "# Session Memory Index",
    "",
    "This index catalogs durable memory distilled from AI agent sessions",
    "(OpenCode, Codex, Claude Code).",
    "",
    "## Entry points",
    "- [[docs/operating-model]] — compile cadence, promotion rules, and the daily ↔ notes boundary.",
    "- Recent daily logs live under `knowledge/daily/` — raw, timestamped session captures awaiting compile.",
    "",
)

INDEX_FOOTER = (
    "## Editorial note",
    "This index is vault metadata — a navigation map over `knowledge/notes/`, not a page derived from `raw/` or `inbox/`. It is regenerated by `scripts/rebuild_memory_index.py`; edits to page titles or one-sentence summaries will be picked up on the next rebuild.",
)

NOTES_PREFIX = "knowledge/notes/"


class IndexCapacityError(ValueError):
    """The shared index cannot admit publication under its configured capacity."""


def build_index_bytes(
    root: Path = ROOT,
    pending: Mapping[str, bytes | None] | None = None,
    *,
    base: Mapping[str, bytes] | None = None,
) -> bytes:
    """Render the index from disk plus unpublished transaction after-images."""
    root = Path(root)
    virtual = _limited_pages(_virtual_pages(root, base, pending), root)
    return _render_index(_index_buckets(_published_only(root, virtual)))


def _virtual_pages(
    root: Path, base: Mapping[str, bytes] | None,
    pending: Mapping[str, bytes | None] | None,
) -> Iterable[tuple[str, bytes]]:
    remaining = dict(pending or {})
    _validate_pending(remaining)
    for relative, content in _limited_pages(_source_pages(root, base), root):
        selected = remaining.pop(relative, content)
        if selected is not None:
            yield relative, selected
    yield from _pending_additions(remaining)


def _pending_additions(remaining: Mapping[str, bytes | None]) -> Iterable[tuple[str, bytes]]:
    return ((relative, content) for relative, content in remaining.items() if content is not None)


def _source_pages(root: Path, base: Mapping[str, bytes] | None) -> Iterable[tuple[str, bytes]]:
    if base is not None:
        yield from base.items()
        return
    notes = root / "knowledge" / "notes"
    for path in notes.rglob("*.md"):
        yield path.relative_to(root).as_posix(), read_stable_bytes(
            path, MAX_PAGE_BYTES, label="knowledge index source"
        )


def _validate_pending(pending: Mapping[str, bytes | None]) -> None:
    for relative, content in pending.items():
        if not relative.startswith("knowledge/notes/"):
            raise ValueError("pending index path is outside knowledge notes")
        if content is not None and len(content) > MAX_PAGE_BYTES:
            raise ValueError("pending index page exceeds limit")


class _IndexBudget:
    """Optional operator quotas, counted without retaining page bodies."""

    def __init__(self, root: Path) -> None:
        self.count = 0
        self.total_bytes = 0
        self.max_pages = setting_value("index.max_pages", root)
        self.max_bytes = setting_value("index.max_total_bytes", root)

    def add(self, content: bytes) -> None:
        self.count += 1
        self.total_bytes += len(content)
        if self.max_pages and self.count > self.max_pages:
            raise IndexCapacityError(f"knowledge index page count exceeds limit; {raise_hint('index.max_pages')}")
        if self.max_bytes and self.total_bytes > self.max_bytes:
            raise IndexCapacityError(f"knowledge index source bytes exceed limit; {raise_hint('index.max_total_bytes')}")


def _limited_pages(pages: Iterable[tuple[str, bytes]], root: Path) -> Iterable[tuple[str, bytes]]:
    budget = _IndexBudget(root)
    for relative, content in pages:
        budget.add(content)
        yield relative, content


def _published_only(root: Path, virtual: Iterable[tuple[str, bytes]]) -> Iterable[tuple[str, bytes]]:
    """Drop the pages this repository does not publish.

    The vault and the public source are one directory and `knowledge/index.md`
    is tracked, so a private page's title reaching the index would put it in a
    public file.
    """
    denials, allowed = _publication_rules(root)
    for relative, content in virtual:
        if _is_public_path(relative, denials, allowed):
            yield relative, content


def published_paths(root: Path, paths: Sequence[str]) -> tuple[list[str], int]:
    """Split paths into the ones this repository publishes and a count of the rest.

    `knowledge/log.md` is tracked in the public source and the compile pass
    appends the pages it touched to it, so a private slug written there is
    personal content in a public file. A vault whose `.gitignore` denies
    nothing publishes everything, and nothing is filtered.
    """
    denials, allowed = _publication_rules(root)
    if not denials:
        return list(paths), 0
    named = [item for item in paths if _is_public_path(item, denials, allowed)]
    return named, len(paths) - len(named)


def _publication_rules(root: Path) -> tuple[set[str], set[str]]:
    """Denied directory prefixes, and the exceptions that publish again.

    A denial covers a directory; an exception names one exact file, or one
    directory when it ends in a slash. Reading an exception as a prefix would
    publish every sibling of the one page that was allowed.
    """
    denials: set[str] = set()
    allowed: set[str] = set()
    for line in _gitignore_lines(root):
        _classify_rule(line, denials, allowed)
    return {item for item in denials if item}, allowed


def _classify_rule(line: str, denials: set[str], allowed: set[str]) -> None:
    if line.startswith("!"):
        allowed.add(line[1:])
        return
    denials.add(_rule_prefix(line))


def _rule_prefix(rule: str) -> str:
    """A rule covers the directory it names; `notes/*.md` covers `notes/`."""
    head, separator, _tail = rule.rpartition("/")
    if not separator:
        return ""
    return f"{head}/"


def _is_public_path(path: str, denials: set[str], allowed: set[str]) -> bool:
    if not any(path.startswith(prefix) for prefix in denials):
        return True
    if path in allowed:
        return True
    return _under_allowed_directory(path, allowed)


def _under_allowed_directory(path: str, allowed: set[str]) -> bool:
    directories = [item for item in allowed if item.endswith("/")]
    return any(path.startswith(item) for item in directories)


def _gitignore_lines(root: Path) -> set[str]:
    try:
        text = (root / ".gitignore").read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return set()
    return {line.strip() for line in text.splitlines() if line.strip()}


def _index_buckets(virtual: Iterable[tuple[str, bytes]]) -> dict[str, list[tuple[str, str]]]:
    buckets: dict[str, list[tuple[str, str]]] = {
        name: [] for name in TYPE_SECTIONS.values()
    }
    buckets["Other"] = []
    for _relative, entry in sorted(_index_entries(virtual)):
        section, link, summary = entry
        buckets[section].append((link, summary))
    return buckets


def _index_entries(virtual: Iterable[tuple[str, bytes]]):
    for relative, raw in virtual:
        entry = _index_entry(relative, raw)
        if entry is not None:
            yield relative, entry


def _index_entry(relative: str, raw: bytes) -> tuple[str, str, str] | None:
    """Section, link and summary for a page, or None when it does not belong."""
    if _excluded_from_index(relative):
        return None
    text = raw.decode("utf-8", errors="strict")
    if _is_retired(text):
        return None
    return _section_of(text), _index_link(relative), _summary_of(text)


def _excluded_from_index(relative: str) -> bool:
    if Path(relative).name in SKIP_NAMES:
        return True
    return "/archive/" in f"/{relative}/"


def _is_retired(text: str) -> bool:
    status = STATUS_RE.search(text)
    if status is None:
        return False
    return is_retired(status.group(1))


def _section_of(text: str) -> str:
    page_type = TYPE_RE.search(text)
    if page_type is None:
        return "Other"
    return TYPE_SECTIONS.get(page_type.group(1).strip().strip("\"'"), "Other")


def _index_link(relative: str) -> str:
    return str(Path(relative).with_suffix("")).replace("\\", "/")


def _summary_of(text: str) -> str:
    summary = SUMMARY_RE.search(text)
    if summary is None:
        return ""
    return summary.group(1).strip()


def _render_index(buckets: Mapping[str, list[tuple[str, str]]]) -> bytes:
    lines = list(INDEX_HEADER)
    for name in [*TYPE_SECTIONS.values(), "Other"]:
        lines.extend(_section_lines(name, buckets.get(name, [])))
    lines.extend(INDEX_FOOTER)
    output = ("\n".join(lines).rstrip() + "\n").encode("utf-8")
    if len(output) > MAX_INDEX_BYTES:
        raise ValueError("knowledge index output exceeds limit")
    return output


def _section_lines(name: str, entries: list[tuple[str, str]]) -> list[str]:
    pages = sorted(set(entries), key=lambda item: item[0].casefold())
    if not pages:
        return []
    return [f"## {name}", *(_page_line(*page) for page in pages), ""]


def _page_line(link: str, summary: str) -> str:
    if not summary:
        return f"- [[{link}]]"
    return f"- [[{link}]] — {summary}"


def main() -> int:
    repair_lineage = ""
    for _ in range(MAX_REBUILD_ATTEMPTS):
        plan = _rebuild_plan(repair_lineage)
        if plan is None:
            print("rebuild_memory_index: knowledge/index.md is current")
            return 0
        operation_id, content, preconditions = plan
        try:
            mutate_knowledge(operation_id, {out: content}, preconditions=preconditions)
            print(f"rebuild_memory_index: knowledge/index.md rebuilt ({len(content)} bytes)")
            return 0
        except TransactionDriftError as exc:
            repair_lineage = exc.transaction_id
        except (TransactionFailure, ValueError) as exc:
            _require_retryable(exc)
    raise RuntimeError("knowledge index rebuild did not converge")


def _rebuild_plan(
    repair_lineage: str,
) -> tuple[str, bytes, dict[str, object]] | None:
    """The write to make, or None when the index already matches the vault."""
    manifest, tree = snapshot_claim_tree_with_content(ROOT)
    notes = {
        path: content
        for path, content in tree.items()
        if path.startswith("knowledge/notes/")
    }
    content = build_index_bytes(ROOT, base=notes)
    before_bytes, before_hash = _current_index()
    if before_bytes == content:
        return None
    generation = str(manifest["absence_generation"])
    return (
        stable_operation_id(
            "rebuild-index", f"{generation}:{before_hash}:{repair_lineage}", content
        ),
        content,
        {
            "claim_tree_manifest": manifest,
            out.relative_to(ROOT).as_posix(): before_hash,
        },
    )


def _current_index() -> tuple[bytes | None, str]:
    try:
        before_bytes = read_stable_bytes(
            out, MAX_INDEX_BYTES, label="knowledge index before-state"
        )
    except FileNotFoundError:
        return None, ABSENT
    return before_bytes, sha256_bytes(before_bytes)


def _require_retryable(exc: BaseException) -> None:
    """A precondition that moved under us is a retry; anything else is not."""
    if isinstance(exc, TransactionFailure) and exc.code == "precondition_failed":
        return
    if isinstance(exc, ValueError) and _is_precondition_drift(exc):
        return
    raise exc


def _is_precondition_drift(exc: ValueError) -> bool:
    return "caller precondition does not match target" in str(exc)


if __name__ == "__main__":
    raise SystemExit(main())
